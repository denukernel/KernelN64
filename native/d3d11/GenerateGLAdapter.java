import java.lang.reflect.*;
import java.nio.file.*;
import java.util.*;

/** Generate mechanical JOGL interface plumbing without a reflective GL proxy.
 * JOGL's large interface exceeds the JVM proxy generator's method-size limit.
 */
class GenerateGLAdapter {
    public static void main(String[] args) throws Exception {
        StringBuilder code=new StringBuilder("package d3d11.bridge.generated;\nimport d3d11.bridge.D3DGlBridge;\n// Generated by native/d3d11/GenerateGLAdapter.java; edit D3DGlBridge for behavior.\npublic final class D3DGL implements javax.media.opengl.GL {\nprivate final D3DGlBridge bridge;\npublic D3DGL(D3DGlBridge bridge){this.bridge=bridge;}\n");
        Method[] methods=Class.forName("javax.media.opengl.GL").getMethods();Arrays.sort(methods,Comparator.comparing(Method::toGenericString));
        for(Method method:methods) {
            if(!Modifier.isAbstract(method.getModifiers()))continue;
            code.append("public ").append(method.getReturnType().getCanonicalName()).append(' ').append(method.getName()).append('(');
            Class<?>[] parameters=method.getParameterTypes();for(int i=0;i<parameters.length;i++){if(i>0)code.append(',');code.append(parameters[i].getCanonicalName()).append(" a").append(i);}
            code.append("){ ");Class<?> result=method.getReturnType();
            if(result!=void.class) {
                code.append("return ");
                if(result.isPrimitive())code.append(result==boolean.class?"((Boolean)":"((Number)");
                else code.append('(').append(result.getCanonicalName()).append(')');
            }
            code.append("bridge.call(\"").append(method.getName()).append("\",new Object[]{");
            for(int i=0;i<parameters.length;i++){if(i>0)code.append(',');code.append('a').append(i);}code.append("})");
            if(result.isPrimitive()&&result!=void.class)code.append(").").append(result.getName()).append("Value()");
            code.append("; }\n");
        }
        code.append("}\n");Files.writeString(Path.of(args[0]),code.toString());
    }
}
